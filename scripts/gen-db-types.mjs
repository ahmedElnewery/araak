// Generates packages/db/src/types.gen.ts from the Development project through the Supabase
// Management API (no database URL, Docker, CLI or MCP).
// `--check` exits non-zero when the committed file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const ref = process.env.SUPABASE_DEV_PROJECT_REF;
const token = process.env.SUPABASE_ACCESS_TOKEN;
if (process.env.SUPABASE_ENV !== "development") throw new Error("SUPABASE_ENV must be 'development'");
if (!ref || !token) throw new Error("SUPABASE_DEV_PROJECT_REF and SUPABASE_ACCESS_TOKEN are required");
if (process.env.SUPABASE_PROD_PROJECT_REF && process.env.SUPABASE_PROD_PROJECT_REF === ref) {
  throw new Error("Refusing: dev ref equals prod ref");
}

const url = `https://api.supabase.com/v1/projects/${ref}/types/typescript?included_schemas=public`;
const res = await fetch(url, { headers: { Authorization: `Bearer ${token}` } });
if (!res.ok) throw new Error(`Type generation failed: ${res.status}`);
const { types } = await res.json();

const out = "packages/db/src/types.gen.ts";
const header = "// Generated by scripts/gen-db-types.mjs. Do not edit.\n";
const next = execFileSync("pnpm", ["exec", "prettier", "--stdin-filepath", out], { input: header + types }).toString();

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== next) {
    console.error("packages/db/src/types.gen.ts is stale; run `pnpm db:types` and commit.");
    process.exit(1);
  }
  console.log("DB types are up to date.");
} else {
  writeFileSync(out, next);
  console.log(`Wrote ${out}`);
}
